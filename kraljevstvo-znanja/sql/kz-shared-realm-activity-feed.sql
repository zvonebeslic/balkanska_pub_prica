-- Private read-only kingdom activity feed. Public access only through membership-checked RPC.
create table if not exists kz_private.realm_events(
 id bigint generated by default as identity primary key,
 kingdom_id uuid not null references public.kz_kingdoms(id) on delete cascade,
 kind text not null,body text not null,event_key text,created_at timestamptz not null default now(),
 unique(kingdom_id,event_key)
);
alter table kz_private.realm_events enable row level security;
revoke all on kz_private.realm_events from public,anon,authenticated;
create index if not exists realm_events_order on kz_private.realm_events(kingdom_id,created_at desc,id desc);
create or replace function kz_private.realm_role_label(role text) returns text language sql immutable set search_path='' as $$
 select case role when 'kralj' then 'kralj' when 'vojvoda' then 'vojvoda' else 'vojnik' end
$$;
create or replace function kz_private.log_realm_event(realm uuid,kind text,body text,event_key text,event_at timestamptz)
returns void language sql set search_path='' as $$
 insert into kz_private.realm_events(kingdom_id,kind,body,event_key,created_at)
 values(realm,kind,body,event_key,event_at) on conflict(kingdom_id,event_key) do nothing
$$;
revoke all on function kz_private.log_realm_event(uuid,text,text,text,timestamptz) from public,anon,authenticated;
create or replace function kz_private.realm_member_joined() returns trigger language plpgsql set search_path='' as $$
declare n text;
begin
 select display_name into n from public.kz_players where id=new.player_id;
 perform kz_private.log_realm_event(new.kingdom_id,case when new.role='kralj' then 'found' else 'join' end,
 coalesce(n,'Igrač')||case when new.role='kralj' then ' osniva kraljevstvo.' else ' pridružuje se kraljevstvu (čin: '||kz_private.realm_role_label(new.role)||').' end,
 null,new.joined_at);
 return new;
end $$;
drop trigger if exists kz_realm_member_joined on public.kz_members;
create trigger kz_realm_member_joined after insert on public.kz_members for each row execute function kz_private.realm_member_joined();
CREATE OR REPLACE FUNCTION public.kz_membership(p_guest_id uuid, p_guest_secret text, p_action text, p_target uuid DEFAULT NULL::uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare v_player uuid; v_king uuid; v_role text; v_target_role text; v_roles jsonb; rec record;
begin
 v_player:=public.kz_who(p_guest_id,p_guest_secret);
 perform 1 from public.kz_players where id=v_player for update;
 select kingdom_id,role into v_king,v_role from public.kz_members where player_id=v_player;
 if v_king is null then raise exception 'Nema aktivnog članstva'; end if;
 perform 1 from public.kz_kingdoms where id=v_king for update;
 select coalesce(jsonb_object_agg(player_id::text,role),'{}'::jsonb) into v_roles from public.kz_members where kingdom_id=v_king;
 if p_action='leave' and v_role<>'kralj' then
   if exists(select 1 from public.kz_games where player_id=v_player and finished_at is null) then raise exception 'Prvo završi pet pitanja'; end if;
   delete from public.kz_members where player_id=v_player;
   perform kz_private.log_realm_event(v_king,'leave',coalesce((select display_name from public.kz_players where id=v_player),'Igrač')||' napušta kraljevstvo.',null,clock_timestamp());
 elsif p_action='close' and v_role='kralj' then
   if (select count(*) from public.kz_members where kingdom_id=v_king)<>1
      or (select area_m2+bank_m2 from public.kz_kingdoms where id=v_king)<>0 then
      raise exception 'Kraljevstvo s članovima ili teritorijem ne može se zatvoriti; predaj krunu';
   end if;
   delete from public.kz_kingdoms where id=v_king;
 elsif p_action in ('crown','duke','kick') and v_role='kralj' and p_target is not null and p_target<>v_player then
   select role into v_target_role from public.kz_members where player_id=p_target and kingdom_id=v_king;
   if v_target_role is null then raise exception 'Odabrani igrač nije član kraljevstva'; end if;
   if p_action='crown' then
     update public.kz_members set role='vojnik' where player_id=v_player;
     update public.kz_members set role='kralj' where player_id=p_target;
     if v_target_role='vojvoda' then update public.kz_members set role='vojvoda' where player_id=v_player; end if;
     insert into public.kz_mail(player_id,body)
      values(p_target,'Predana ti je kruna kraljevstva '||(select name from public.kz_kingdoms where id=v_king)||'.');
   elsif p_action='duke' then
     update public.kz_members set role='vojnik' where kingdom_id=v_king and role='vojvoda' and player_id<>p_target;
     update public.kz_members set role='vojvoda' where player_id=p_target;
   else
     if exists(select 1 from public.kz_games where player_id=p_target and finished_at is null) then raise exception 'Igrač prvo mora završiti pitanja'; end if;
     delete from public.kz_members where player_id=p_target;
     perform kz_private.log_realm_event(v_king,'kick',coalesce((select display_name from public.kz_players where id=p_target),'Igrač')||' je isključen iz kraljevstva. Odluka: '||coalesce((select display_name from public.kz_players where id=v_player),'kralj')||'.',null,clock_timestamp());
     insert into public.kz_mail(player_id,body) values(p_target,'Više nisi član kraljevstva '||(select name from public.kz_kingdoms where id=v_king)||'.');
   end if;
 else
   raise exception 'Nemaš ovlast za ovu radnju';
 end if;
 for rec in select m.player_id,m.role,p.display_name,v_roles->>m.player_id::text old_role
   from public.kz_members m join public.kz_players p on p.id=m.player_id
   where m.kingdom_id=v_king and v_roles ? m.player_id::text and (v_roles->>m.player_id::text) is distinct from m.role
 loop
   perform kz_private.log_realm_event(v_king,
    case when (case rec.role when 'kralj' then 3 when 'vojvoda' then 2 else 1 end) >
       (case rec.old_role when 'kralj' then 3 when 'vojvoda' then 2 else 1 end) then 'promotion' else 'demotion' end,
    rec.display_name||': '||kz_private.realm_role_label(rec.old_role)||' → '||kz_private.realm_role_label(rec.role)||'.',null,clock_timestamp());
 end loop;
 return jsonb_build_object('ok',true);
end $function$
;
-- The existing membership function logs final role changes rather than transient intermediate roles in a crown transfer.
create or replace function kz_private.record_realm_battle(d kz_private.territory_duels,stage text,event_at timestamptz)
returns void language plpgsql set search_path='' as $$
declare an text;dn text;ap text;dp text; suffix text; key text; a_kind text;d_kind text; a_body text;d_body text;
begin
 select name into an from public.kz_kingdoms where id=d.attacker;
 select name into dn from public.kz_kingdoms where id=d.defender;
 select display_name into ap from public.kz_players where id=d.attacker_player;
 select display_name into dp from public.kz_players where id=d.defender_player;
 key:='battle:'||d.id::text||':'||stage;
 if stage='start' then
   a_kind:='battle_start';d_kind:='battle_start';
   a_body:=coalesce(ap,'Naše kraljevstvo')||' započinje napad na '||dn||'.';
   d_body:=an||' napada naše kraljevstvo'||case when ap is not null then ' (napadač: '||ap||')' else '' end||'.';
 elsif stage='defense' then
   a_kind:='battle_defense';d_kind:='battle_defense';
   a_body:=coalesce(dp,'Branitelj')||' iz kraljevstva '||dn||' uključuje se u obranu.';
   d_body:=coalesce(dp,'Naš član')||' uključuje se u obranu našeg teritorija od kraljevstva '||an||'.';
 else
   suffix:=' Napredak: '||d.hits||'/'||d.required_hits||'.';
   if d.status='won' then
     a_kind:='victory';d_kind:='defeat';
     a_body:='Pobjeda! Osvojen blok od 20 m² kraljevstva '||dn||'.'||suffix;
     d_body:='Poraz. Kraljevstvo '||an||' osvojilo je naš blok od 20 m².'||suffix;
   elsif d.status='lost' then
     a_kind:='defeat';d_kind:='victory';
     a_body:='Poraz. Napad na kraljevstvo '||dn||' nije uspio.'||suffix;
     d_body:='Pobjeda! Teritorij obranjen od kraljevstva '||an||'.'||suffix;
   else
     a_kind:='battle_end';d_kind:='battle_end';
     a_body:='Okršaj s kraljevstvom '||dn||' je prekinut.';d_body:='Okršaj s kraljevstvom '||an||' je prekinut.';
   end if;
   if ap is not null then a_body:=a_body||' Napadač: '||ap||'.';d_body:=d_body||' Napadač: '||ap||'.';end if;
   if dp is not null then a_body:=a_body||' Branitelj: '||dp||'.';d_body:=d_body||' Branitelj: '||dp||'.';end if;
 end if;
 if an is not null and dn is not null then
   perform kz_private.log_realm_event(d.attacker,a_kind,a_body,key,event_at);
   perform kz_private.log_realm_event(d.defender,d_kind,d_body,key,event_at);
 end if;
end $$;
revoke all on function kz_private.record_realm_battle(kz_private.territory_duels,text,timestamptz) from public,anon,authenticated;
create or replace function kz_private.realm_battle_event() returns trigger language plpgsql set search_path='' as $$
begin
 if tg_op='INSERT' then
   perform kz_private.record_realm_battle(new,'start',new.created_at);
 else
   if old.defender_player is null and new.defender_player is not null then perform kz_private.record_realm_battle(new,'defense',clock_timestamp());end if;
   if old.status='active' and new.status<>'active' then perform kz_private.record_realm_battle(new,'finish',coalesce(new.finished_at,clock_timestamp()));end if;
 end if;
 return new;
end $$;
drop trigger if exists kz_realm_battle_event on kz_private.territory_duels;
create trigger kz_realm_battle_event after insert or update on kz_private.territory_duels for each row execute function kz_private.realm_battle_event();
-- Backfill only known membership dates and recorded battles, without inventing past promotions or exits.
insert into kz_private.realm_events(kingdom_id,kind,body,event_key,created_at)
 select m.kingdom_id,'join',p.display_name||' – član kraljevstva od ovog datuma.','member-backfill:'||m.player_id::text,m.joined_at
 from public.kz_members m join public.kz_players p on p.id=m.player_id on conflict do nothing;
do $$ declare d kz_private.territory_duels%rowtype;begin
 for d in select * from kz_private.territory_duels loop
  perform kz_private.record_realm_battle(d,'start',d.created_at);
  if d.status<>'active' then perform kz_private.record_realm_battle(d,'finish',coalesce(d.finished_at,d.activity_at,d.created_at));end if;
 end loop;
end $$;
create or replace function kz_private.realm_guardian_event() returns trigger language plpgsql set search_path='' as $$
declare n text; k text;
begin
 select display_name into n from public.kz_players where id=new.player_id;
 select kind into k from public.kz_guardian_catalog where guardian_id=new.guardian_id;
 perform kz_private.log_realm_event(new.kingdom_id,'guardian',
  coalesce(n,'Član kraljevstva')||' pobjeđuje čuvara ('||case k when 'castle' then 'Hodajući dvorac' when 'iron' then 'Sir Željeznik' when 'forest' then 'Čarobna šuma' else 'čuvar znanja' end||') i donosi '||new.reward_m2||' m² na zajedničko konto.',
  'guardian:'||new.guardian_id||':'||new.generation,new.awarded_at);
 return new;
end $$;
