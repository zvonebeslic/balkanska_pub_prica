create or replace function public.kz_realm_notifications(p_guest_id uuid,p_guest_secret text,p_before bigint default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare player uuid;realm uuid;cut timestamptz; result jsonb;
begin
 player:=public.kz_who(p_guest_id,p_guest_secret);
 select kingdom_id into realm from public.kz_members where player_id=player;
 if realm is null then return jsonb_build_object('kingdom_id',null,'events','[]'::jsonb,'has_more',false);end if;
 if p_before is not null then
  select created_at into cut from kz_private.realm_events where kingdom_id=realm and id=p_before;
  if cut is null then return jsonb_build_object('kingdom_id',realm,'events','[]'::jsonb,'has_more',false);end if;
 end if;
 with page as (select id,kind,body,created_at at from kz_private.realm_events
  where kingdom_id=realm and (p_before is null or (created_at,id)<(cut,p_before))
  order by created_at desc,id desc limit 51),
 first_page as (select * from page order by at desc,id desc limit 50)
 select jsonb_build_object('kingdom_id',realm,'events',coalesce((select jsonb_agg(to_jsonb(f) order by f.at,f.id) from first_page f),'[]'::jsonb),
 'has_more',(select count(*)>50 from page)) into result;
 return result;
end $$;
revoke all on function public.kz_realm_notifications(uuid,text,bigint) from public;
grant execute on function public.kz_realm_notifications(uuid,text,bigint) to anon,authenticated;
