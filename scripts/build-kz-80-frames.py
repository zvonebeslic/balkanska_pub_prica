#!/usr/bin/env python3
"""Build seven genuine 80-image RGBA sprite atlases for Kraljevstvo znanja.

Raster characters: original 40 frames + 40 motion-compensated optical-flow
in-between renders, one in-between for each original transition including
the loop seam. Not a copy/paste or plain alpha crossfade.

SVG characters: 80 unique vector poses rasterized at full per-frame quality.
One frame atlas per type, used by all instances of that type.
"""
from __future__ import annotations
import base64
import io
import json
import math
import re
import subprocess
from copy import deepcopy
from pathlib import Path
from xml.etree import ElementTree as ET

import cv2
import numpy as np
from PIL import Image
import cairosvg

ROOT = Path(__file__).resolve().parent.parent
GAME = ROOT / "kraljevstvo-znanja"
FRAMES = 80
COLS = 10
ROWS = 8
SMALL_SIZE = 160

OLD_RASTER = {
    "castle": ("kz-roaming-castle-atlas.js", "kz-roaming-castle-atlas-80.js",
               "KZ_ROAMING_CASTLE_WEBP", 192),
    "iron": ("kz-sir-zeljeznik-optical-40.js", "kz-sir-zeljeznik-80.js",
             "KZ_IRON_ROBOT_ATLAS", 224),
}

def read_webp_from_js(path: Path) -> Image.Image:
    text = path.read_text(encoding="utf-8")
    match = re.search(r'data:image/webp;base64,([A-Za-z0-9+/=]+)', text)
    if not match:
        raise ValueError(f"WebP content is absent from {path}")
    return Image.open(io.BytesIO(base64.b64decode(match.group(1)))).convert("RGBA")


def unpack(source: Image.Image, width: int) -> list[Image.Image]:
    if source.width % width or source.height % width:
        raise ValueError(f"Invalid input atlas {source.size}, frame {width}")
    cols, rows = source.width // width, source.height // width
    if cols * rows != 40:
        raise ValueError(f"Expected precisely 40 original frames, got {cols*rows}")
    return [
        source.crop((i % cols * width, i // cols * width,
                     (i % cols + 1) * width, (i // cols + 1) * width))
        for i in range(40)
    ]


def premultiplied(array: np.ndarray) -> np.ndarray:
    f = array.astype(np.float32) / 255.0
    f[:, :, :3] *= f[:, :, 3:4]
    return f


def motion_midpoint(before: Image.Image, after: Image.Image) -> Image.Image:
    """Two-sided dense optical flow at t=0.5, in premultiplied RGBA."""
    a = np.asarray(before, dtype=np.uint8)
    b = np.asarray(after, dtype=np.uint8)
    fa, fb = premultiplied(a), premultiplied(b)
    ag = cv2.cvtColor((fa[:, :, :3] * 255).astype(np.uint8), cv2.COLOR_RGB2GRAY)
    bg = cv2.cvtColor((fb[:, :, :3] * 255).astype(np.uint8), cv2.COLOR_RGB2GRAY)
    forward = cv2.calcOpticalFlowFarneback(
        ag, bg, None, 0.5, 3, 19, 3, 5, 1.1, 0)
    backward = cv2.calcOpticalFlowFarneback(
        bg, ag, None, 0.5, 3, 19, 3, 5, 1.1, 0)
    h, w = ag.shape
    xs, ys = np.meshgrid(np.arange(w, dtype=np.float32),
                         np.arange(h, dtype=np.float32))
    warp_a = cv2.remap(fa, xs - 0.5 * forward[:, :, 0],
                       ys - 0.5 * forward[:, :, 1],
                       cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT)
    warp_b = cv2.remap(fb, xs - 0.5 * backward[:, :, 0],
                       ys - 0.5 * backward[:, :, 1],
                       cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT)
    both = (warp_a + warp_b) * 0.5
    alpha = np.clip(both[:, :, 3:4], 0, 1)
    rgb = np.clip(both[:, :, :3] / np.maximum(alpha, 1e-6), 0, 1)
    result = np.concatenate([rgb, alpha], axis=2)
    result = np.clip(result * 255 + 0.5, 0, 255).astype(np.uint8)
    result[alpha[:, :, 0] < 1 / 255, :] = 0
    return Image.fromarray(result, "RGBA")


def compose(frames: list[Image.Image], px: int) -> Image.Image:
    if len(frames) != FRAMES:
        raise AssertionError("A character must have exactly 80 frames")
    sheet = Image.new("RGBA", (COLS * px, ROWS * px), (0, 0, 0, 0))
    for i, frame in enumerate(frames):
        if frame.size != (px, px):
            raise ValueError(f"Frame {i} size {frame.size} differs from {px}")
        sheet.paste(frame, (i % COLS * px, i // COLS * px))
    return sheet


def webp_data(image: Image.Image) -> str:
    buf = io.BytesIO()
    image.save(buf, "WEBP", quality=94, method=6, exact=True)
    data = buf.getvalue()
    if Image.open(io.BytesIO(data)).size != image.size:
        raise AssertionError("WebP roundtrip verification failed")
    return "data:image/webp;base64," + base64.b64encode(data).decode("ascii")


def emit_js(path: Path, global_name: str, data: str, name: str):
    path.write_text(
        f"/* {name}: exactly 80 rendered frames, 10x8 atlas, transparent WebP. "
        "Auto-generated by scripts/build-kz-80-frames.py; do not hand-edit. */\n"
        f"window.{global_name} = {json.dumps(data, ensure_ascii=False)};\n",
        encoding="utf-8",
    )


def build_raster():
    for kind, (source, output, global_name, px) in OLD_RASTER.items():
        frames = unpack(read_webp_from_js(GAME / source), px)
        doubled: list[Image.Image] = []
        for i in range(40):
            doubled.append(frames[i])
            doubled.append(motion_midpoint(frames[i], frames[(i+1) % 40]))
        unique = len({frame.tobytes() for frame in doubled})
        if unique < 75:
            raise ValueError(f"{kind}: {unique}/80 unique frames")
        data = webp_data(compose(doubled, px))
        emit_js(GAME / output, global_name, data, kind)
        print(f"OK {kind}: 80 frames, 10x8 x {px}px; {unique} unique; {len(data):,} chars")


def original_svgs() -> dict[str, str]:
    node = """
        global.window = {};
        require('./kraljevstvo-znanja/kz-world-registry.js');
        process.stdout.write(JSON.stringify(window.KZWorldRegistry.svgSprites));
    """
    out = subprocess.check_output(["node", "-e", node], cwd=ROOT, text=True)
    return json.loads(out)


def change_transform(root: ET.Element, class_name: str,
                     transform: str | None = None, opacity: float | None = None):
    for el in root.iter():
        if class_name in el.attrib.get("class", "").split():
            if transform is not None:
                el.set("transform", transform)
            if opacity is not None:
                el.set("opacity", f"{opacity:.5f}")


def create_pose(original: str, kind: str, i: int) -> Image.Image:
    root = ET.fromstring(original)
    t = 2 * math.pi * i / FRAMES
    swing = math.sin(t)
    wing = math.sin(2 * t)
    float_y = 0.9 * math.sin(t - 0.5)
    # Keep painted floor shadow stationary; animate body above it.
    children = list(root)
    if children:
        body = ET.Element("{http://www.w3.org/2000/svg}g")
        body.set("transform", f"translate(0 {float_y:.5f})")
        for child in children[1:]:
            root.remove(child)
            body.append(child)
        root.append(body)
    if kind == "dragon":
        change_transform(root, "life-wing-left", f"rotate({-8+21*wing:.5f} 49 48)")
        change_transform(root, "life-wing-right", f"rotate({8-21*wing:.5f} 64 47)")
        # Smooth intermittent breath of fire, not an abrupt flashing frame.
        pulse = max(0.0, math.sin(t - 0.9)) ** 3
        change_transform(root, "life-flame",
                         f"translate({2*pulse:.4f} 0) scale({1+0.13*pulse:.4f} 1)",
                         0.05 + 0.95 * pulse)
    elif kind == "knight":
        change_transform(root, "life-leg-left", f"rotate({11*swing:.4f} 41 83)")
        change_transform(root, "life-leg-right", f"rotate({-11*swing:.4f} 62 84)")
        change_transform(root, "life-sword", f"rotate({-12+16*math.sin(t+0.6):.4f} 76 48)")
        change_transform(root, "life-cape", f"rotate({2.8*math.sin(t-0.9):.4f} 48 52)")
    elif kind == "owl":
        change_transform(root, "life-owl-wing-left", f"rotate({-5+17*wing:.4f} 32 55)")
        change_transform(root, "life-owl-wing-right", f"rotate({5-17*wing:.4f} 77 56)")
        blink_phase = i % 80
        blink = 1.0 - 0.92 * max(0, 1-abs(blink_phase-63)/3)
        change_transform(root, "life-blink", f"translate(0 {48*(1-blink):.5f}) scale(1 {blink:.5f})")
    elif kind == "wizard":
        change_transform(root, "life-wizard-arm", f"rotate({14*swing:.5f} 68 62)")
        change_transform(root, "life-star", f"rotate({i*4.5:.4f} 88 16)",
                         0.7+0.3*abs(math.sin(2*t)))
    elif kind == "banner":
        change_transform(root, "life-flag",
                         f"translate({3*math.sin(t):.5f} 0) "
                         f"translate(21 0) scale({1-0.07*math.cos(2*t):.5f} 1) translate(-21 0)")
    else:
        raise ValueError("Unknown vector character " + kind)
    png = cairosvg.svg2png(bytestring=ET.tostring(root),
                           output_width=SMALL_SIZE, output_height=SMALL_SIZE)
    image = Image.open(io.BytesIO(png)).convert("RGBA")
    return image


def build_vectors():
    svgs = original_svgs()
    expected = ["dragon", "knight", "owl", "wizard", "banner"]
    if not all(name in svgs for name in expected):
        raise ValueError("Expected all five SVG character source drawings")
    output: dict[str, str] = {}
    for kind in expected:
        images = [create_pose(svgs[kind], kind, i) for i in range(FRAMES)]
        unique = len({frame.tobytes() for frame in images})
        if unique < 75:
            raise ValueError(f"{kind}: only {unique} distinct poses")
        output[kind] = webp_data(compose(images, SMALL_SIZE))
        print(f"OK {kind}: 80 unique SVG-rendered poses, 10x8 x {SMALL_SIZE}px")
    dest = GAME / "kz-small-world-80.js"
    dest.write_text(
        "/* Five original illustrated species, 80 unique RGBA frames each, "
        "10x8, 160x160. Generated from the central SVG catalog. */\n"
        + "window.KZ_SMALL_80 = Object.freeze("
        + json.dumps(output, ensure_ascii=False, separators=(",", ":"))
        + ");\n", encoding="utf-8")
    print(f"OK {dest.name}: {dest.stat().st_size:,} bytes")


def main():
    build_raster()
    build_vectors()


if __name__ == "__main__":
    main()
